import { Injectable, Logger } from '@nestjs/common';
import type { AgentProviderId } from '../agent-runtime/agent-runtime.types.js';
import {
  TextAgentGenerationService,
  type TextAgentProvider,
} from '../agent-generation/text-agent-generation.service.js';

const MAX_PROMPT_CHARS = 4000;
type SDKUserMessage = import('@anthropic-ai/claude-agent-sdk').SDKUserMessage;

@Injectable()
export class SessionTitleService {
  private readonly logger = new Logger(SessionTitleService.name);

  constructor(
    private readonly textAgentGenerationService: TextAgentGenerationService,
  ) {}

  isAutoGeneratedName(name: string | null | undefined): boolean {
    return typeof name === 'string' && /^Session \d+$/.test(name.trim());
  }

  async generate(
    worktreePath: string,
    prompt: string,
    provider: AgentProviderId = 'claude',
  ): Promise<string | null> {
    const startedAtMs = Date.now();
    const promptLength = prompt.length;
    this.logger.log(
      `Session title generation requested provider=${provider} worktreePath=${JSON.stringify(worktreePath)} promptLength=${promptLength} promptTruncated=${promptLength > MAX_PROMPT_CHARS}`,
    );

    const titleProvider = this.normalizeProvider(provider);
    if (!titleProvider) {
      this.logger.warn(
        `Session title generation skipped because provider is unsupported provider=${provider} worktreePath=${JSON.stringify(worktreePath)}`,
      );
      return null;
    }

    this.logger.debug(
      `Session title query starting provider=${titleProvider} worktreePath=${JSON.stringify(worktreePath)} promptLength=${promptLength}`,
    );

    const titlePrompt = [
      "Name this session based on the user's first message.",
      'Respond immediately with a broad short title from the first message only.',
      'Do not use tools, investigate, browse, inspect files, or dig into details.',
      'Return only the session name, with no quotes, markdown, or commentary.',
      'Rules:',
      '- 3 to 5 words maximum',
      '- summarize the likely overall task broadly',
      '- use title case or compact sentence case',
      '- do not include trailing punctuation',
      '',
      'First message:',
      prompt.slice(0, MAX_PROMPT_CHARS),
    ].join('\n');

    const result = await this.textAgentGenerationService.generate({
      provider: titleProvider,
      worktreePath,
      taskName: 'session-title',
      // Keep Claude on streaming prompt mode. The main agent UI uses this path
      // successfully, while the SDK one-shot string path can take a different
      // Claude Code auth route and incorrectly report "Not logged in".
      prompt:
        titleProvider === 'claude'
          ? this.createPromptIterable(titlePrompt)
          : titlePrompt,
      claude: {
        maxTurns: 1,
        persistSession: false,
        settingSources: ['project', 'user', 'local'],
        allowedTools: [],
        canUseTool: () =>
          Promise.resolve({
            behavior: 'deny' as const,
            message: 'Tool use disabled for session title generation',
          }),
      },
    });

    if (!result) {
      this.logger.warn(
        `Session title generation returned no result provider=${titleProvider} worktreePath=${JSON.stringify(worktreePath)} elapsedMs=${Date.now() - startedAtMs}`,
      );
      return null;
    }

    const title = this.normalize(result.text);
    if (title === null) {
      this.logger.warn(
        `Title normalization returned null provider=${result.provider} model=${JSON.stringify(result.model)} worktreePath=${JSON.stringify(worktreePath)} elapsedMs=${Date.now() - startedAtMs} rawReply=${JSON.stringify(result.text)}`,
      );
    } else {
      this.logger.log(
        `Session title generated provider=${result.provider} model=${JSON.stringify(result.model)} worktreePath=${JSON.stringify(worktreePath)} elapsedMs=${Date.now() - startedAtMs} rawReplyLength=${result.text.length} title=${JSON.stringify(title)}`,
      );
    }
    return title;
  }

  private normalize(rawTitle: string): string | null {
    const cleaned = rawTitle
      .replace(/```[\s\S]*?```/g, (block) =>
        block.replace(/```[a-zA-Z]*|```/g, ''),
      )
      .replace(/^[\s"'`*_#>-]+|[\s"'`*_#>-]+$/g, '')
      .replace(/[.!?;:,\s"'`*_#>-]+$/g, '')
      .replace(/\s+/g, ' ')
      .trim();

    if (!cleaned) return null;
    const title = cleaned
      .split(' ')
      .filter(Boolean)
      .slice(0, 5)
      .join(' ')
      .trim();
    return title || null;
  }

  private async *createPromptIterable(
    prompt: string,
  ): AsyncIterable<SDKUserMessage> {
    yield {
      type: 'user',
      message: {
        role: 'user',
        content: prompt,
      },
    } as SDKUserMessage;
  }

  private normalizeProvider(
    provider: AgentProviderId,
  ): TextAgentProvider | null {
    return provider === 'claude' || provider === 'codex' || provider === 'pi'
      ? provider
      : null;
  }
}
