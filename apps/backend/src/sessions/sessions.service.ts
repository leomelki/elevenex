  async findOne(id: number) {
    const rows = await this.db
      .select({
        session: schema.sessions,
        projectId: schema.repos.projectId,
        repoColor: schema.repos.color,
        workspaceName: schema.workspaces.name,
        workspaceArchivedAt: schema.workspaces.archivedAt,
        workspaceTaskState: schema.workspaces.taskState,
      })
      .from(schema.sessions)
      .innerJoin(schema.repos, eq(schema.sessions.repoId, schema.repos.id))
      .leftJoin(
        schema.workspaces,
        eq(schema.sessions.workspaceId, schema.workspaces.id),
      )
      .where(eq(schema.sessions.id, id));

    if (rows.length === 0) {
      throw new NotFoundException(`Session with id ${id} not found`);
    }

    const {
      session,
      projectId,
      repoColor,
      workspaceName,
      workspaceArchivedAt,
      workspaceTaskState,
    } = rows[0];
    return this.withInferredActiveAgentProvider({
      ...session,
      projectId,
      repoColor,
      workspaceName,
      workspaceArchivedAt,
      workspaceTaskState,
    });
  }

