  async updateStatus(id: number, status: string) {
    if (!VALID_STATUSES.includes(status as SessionStatus)) {
      throw new BadRequestException(
        `Invalid status: ${status}. Must be one of: ${VALID_STATUSES.join(', ')}`,
      );
    }

    // A turn admitted just before a group archive may still try to mark
    // itself active while its runtime is shutting down.
    if (status !== 'archived' && this.archivingGroup.has(id))
      throw new ConflictException('Session archive is already in progress.');
    const rows = this.db
      .update(schema.sessions)
      .set({
        status,
        updatedAt: new Date().toISOString(),
      })
      .where(eq(schema.sessions.id, id))
      .returning()
      .all();

    if (rows.length === 0) {
      throw new NotFoundException(`Session with id ${id} not found`);
    }

    this.navigationEvents?.invalidate();
    this.emit('session-status-changed', { sessionId: id, status });
    return this.withInferredActiveAgentProvider(rows[0]);
  }

  async markCompletionUnreviewed(
    id: number,
    completionKind: SessionCompletionKind = 'completed',
  ) {
    if (!VALID_COMPLETION_KINDS.includes(completionKind)) {
      throw new BadRequestException(
        `Invalid completion kind: ${completionKind}. Must be one of: ${VALID_COMPLETION_KINDS.join(', ')}`,
      );
    }

    const rows = this.db.transaction(tx => {
      const previous = tx.select({ at: schema.sessions.lastCompletionAt }).from(schema.sessions)
        .where(eq(schema.sessions.id, id)).get()?.at;
      // Completion versions must remain distinct even when two fast turns finish in one millisecond.
      const completedAt = new Date(Math.max(Date.now(), previous ? Date.parse(previous) + 1 : 0)).toISOString();
      return tx.update(schema.sessions)
      .set({
        hasUnreviewedCompletion: true,
        lastCompletionAt: completedAt,
        lastCompletionKind: completionKind,
        updatedAt: new Date().toISOString(),
      })
      .where(eq(schema.sessions.id, id))
      .returning().all();
    }, { behavior: 'immediate' });

    if (rows.length === 0) {
      throw new NotFoundException(`Session with id ${id} not found`);
    }

    const session = rows[0];
    this.navigationEvents?.invalidate();
    this.emit('session-completion-changed', {
      sessionId: id,
      hasUnreviewedCompletion: session.hasUnreviewedCompletion,
      lastCompletionAt: session.lastCompletionAt,
      lastCompletionKind: session.lastCompletionKind,
    });
    return this.withInferredActiveAgentProvider(session);
  }

  async markCompletionReviewed(id: number, expectedCompletionAt?: string) {
    const rows = await this.db
      .update(schema.sessions)
      .set({
        hasUnreviewedCompletion: false,
        updatedAt: new Date().toISOString(),
      })
      .where(and(
        eq(schema.sessions.id, id),
        expectedCompletionAt === undefined ? undefined : eq(schema.sessions.lastCompletionAt, expectedCompletionAt),
        expectedCompletionAt === undefined ? undefined : eq(schema.sessions.hasUnreviewedCompletion, true),
      ))
      .returning();

    if (rows.length === 0) {
      // A delayed viewer must never acknowledge a newer completion. Legacy
      // callers that omit the version retain their unconditional behavior.
      if (expectedCompletionAt !== undefined) return this.findOne(id);
      throw new NotFoundException(`Session with id ${id} not found`);
    }

    const session = rows[0];
    this.navigationEvents?.invalidate();
    this.emit('session-completion-changed', {
      sessionId: id,
      hasUnreviewedCompletion: session.hasUnreviewedCompletion,
      lastCompletionAt: session.lastCompletionAt,
      lastCompletionKind: session.lastCompletionKind,
    });
    return this.withInferredActiveAgentProvider(session);
  }

