  private async cleanupArchivedSessionProcesses(
    id: number,
    requireCleanup = false,
  ) {
    let cleanupError: unknown;
    try {
      await this.agentRuntimeCleanup.cleanupSession(id);
    } catch (error) {
      cleanupError = error;
      this.logger.error(
        `Failed to clean up agent runtime while archiving session ${id}`,
        error instanceof Error ? error.stack : String(error),
      );
    } finally {
      if (requireCleanup) await this.ptyManager.stopForTask(id);
      else {
        this.ptyManager.kill(id);
        await this.ptyManager.killTmuxSession(id);
      }
    }
    if (requireCleanup && cleanupError)
      throw cleanupError instanceof Error
        ? cleanupError
        : new Error('Agent runtime cleanup failed.', { cause: cleanupError });
  }

  async archiveAllByRepo(repoId: number, requireCleanup = false) {
    const sessions = await this.db
      .select({ id: schema.sessions.id })
      .from(schema.sessions)
      .where(eq(schema.sessions.repoId, repoId));
    await this.archiveSessionRows(sessions, requireCleanup);
  }

  private async archiveSessionRows(
    rows: { id: number }[],
    requireCleanup: boolean,
  ) {
    await this.runArchiveCleanup(rows, id => this.archiveAndStop(id, requireCleanup));
  }

  private async runArchiveCleanup(
    rows: readonly { id: number }[],
    cleanup: (id: number) => Promise<unknown>,
  ) {
    // Bound subprocess concurrency and await every cleanup, including failures,
    // before a caller can remove a repository with thousands of conversations.
    const pending = rows.values();
    const errors: unknown[] = [];
    await Promise.all(
      Array.from({ length: Math.min(8, rows.length) }, async () => {
        for (const session of pending) {
          try {
            await cleanup(session.id);
          } catch (error) {
            errors.push(error);
          }
        }
      }),
    );
    if (errors.length)
      throw errors[0] instanceof Error
        ? errors[0]
        : new Error('Agent runtime cleanup failed.', { cause: errors[0] });
  }

  async archiveAllByProject(projectId: number, requireCleanup = false) {
    const sessions = await this.db
      .select({ id: schema.sessions.id })
      .from(schema.sessions)
      .innerJoin(schema.repos, eq(schema.sessions.repoId, schema.repos.id))
      .where(
        and(
          eq(schema.repos.projectId, projectId),
          requireCleanup ? undefined : ne(schema.sessions.status, 'archived'),
        ),
      );

    if (requireCleanup) await this.archiveSessionRows(sessions, true);
    else await Promise.all(sessions.map((s) => this.archive(s.id)));
  }

  async unarchive(id: number) {
    const session = await this.findOne(id);

    if (this.archivingGroup.has(id))
      throw new ConflictException('Session archive is already in progress.');
    if (session.status !== 'archived') {
      throw new BadRequestException('Only archived sessions can be unarchived');
    }
    if (session.folderId) {
      const folder = await this.db
        .select({ archivedAt: schema.sessionFolders.archivedAt })
        .from(schema.sessionFolders)
        .where(eq(schema.sessionFolders.id, session.folderId));
      if (folder[0]?.archivedAt) {
        throw new BadRequestException('Unarchive the folder first');
      }
    }
    await this.assertSessionWorkspaceLinked(session.id);
    await this.reactivateRuntime(id);

    const updated = await this.updateStatus(id, 'stopped');
    if (!updated.archivedByFolder) return updated;
    const rows = await this.db
      .update(schema.sessions)
      .set({ archivedByFolder: false, updatedAt: new Date().toISOString() })
      .where(eq(schema.sessions.id, id))
      .returning();
    return this.withInferredActiveAgentProvider(rows[0]);
  }

  async reactivateRuntime(id: number): Promise<void> {
    await this.agentRuntimeCleanup.reactivateSession?.(id);
  }

  async reset(id: number) {
    const session = await this.findOne(id);
    await this.assertSessionWorkspaceLinked(id);

    // 1. Archive current
    await this.archive(id);

    // 2. Create new session in same worktree
    const newSession = await this.create({
      repoId: session.repoId,
      workspaceId: session.workspaceId ?? undefined,
      folderId: session.folderId ?? undefined,
      branchName: session.branchName,
      worktreePath: session.worktreePath,
      name: `${session.name} (reset)`,
      activeAgentProvider: session.activeAgentProvider,
    });

    return newSession;
  }

  /**
   * Fork a session - creates a new session in the same worktree.
   * The new session is independent and will spawn its own PTY.
   */
  async fork(id: number, name?: string) {
    const session = await this.findOne(id);
    await this.assertSessionWorkspaceLinked(id);

    // Generate fork name
    const forkName = name ?? `${session.name ?? 'Session'} (fork)`;

    // Create new session in same worktree
    const newSession = await this.create({
      repoId: session.repoId,
      workspaceId: session.workspaceId ?? undefined,
      folderId: session.folderId ?? undefined,
      branchName: session.branchName,
      worktreePath: session.worktreePath,
      name: forkName,
      activeAgentProvider: session.activeAgentProvider,
    });

    return newSession;
  }

  /**
   * Kill a session - terminates the PTY process but keeps session accessible.
   * Session status is set to 'stopped' (distinct from 'archived').
   */
  async kill(id: number) {
    const session = await this.findOne(id);

    if (session.status === 'archived') {
      throw new BadRequestException('Archived sessions cannot be stopped');
    }

    try {
      await this.agentRuntimeCleanup.cleanupSession(id);
    } finally {
      // 1. Kill the PTY process if running
      this.ptyManager.kill(id);

      // 2. Kill the tmux session if exists
      await this.ptyManager.killTmuxSession(id);
    }

    // 3. Update status to stopped (NOT archived - session remains accessible)
    return this.updateStatus(id, 'stopped');
  }

  async start(
    id: number,
  ): Promise<{ success: boolean; resumed: boolean; error?: string }> {
    // Just return session info - actual PTY spawn happens via TerminalService
    // when WebSocket connects
    const session = await this.findOne(id);

    if (session.status === 'archived') {
      throw new BadRequestException('Archived sessions cannot be started');
    }
    await this.assertSessionWorkspaceLinked(id);

    // Update status to indicate starting
    await this.reactivateRuntime(id);
    await this.updateStatus(id, 'active');

    return { success: true, resumed: false };
  }

