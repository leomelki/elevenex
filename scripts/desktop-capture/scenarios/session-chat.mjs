import assert from 'node:assert/strict';

/** Real production chat/composer, with the preview-only harness adapter. */
export default async function* (capture) {
  await capture.evaluate(() => { location.href = '/connected-workspace'; });
  await capture.waitFor(() => document.querySelector('ex-workspace-navigation ex-task-list'));
  const owner = (fn, data) => capture.component('ex-machine-workspace', fn, data);
  const finish = async () => { await capture.settle(); await capture.waitFor(() => document.getAnimations().every(a => !Number.isFinite(a.effect?.getComputedTiming().endTime) || a.playState !== 'running')); };
  const mode = value => capture.component('ex-connected-workspace-demo', (component, value) => component.fixture.chat.scenario(value), value);
  await owner(component => component.store.selectSession({ taskId: '11', sessionId: '101' }));
  await capture.waitFor(() => document.querySelector('ex-session-chat .provider')?.textContent.toLowerCase().includes('codex'));
  for (const theme of ['light', 'dark']) {
    await capture.viewport(1440, 960); await capture.theme(theme); await mode('ready');
    await capture.waitFor(() => document.querySelector('ex-session-chat .provider')?.textContent.toLowerCase().includes('codex'));
    await finish();
    yield { name: `${theme}-chat`, inspect: ['ex-session-chat', 'ex-composer', 'ex-chat-scroll', 'ex-turn'] };
    await capture.click('ex-turn .work');
    await capture.waitFor(() => document.querySelector('ex-turn .work')?.getAttribute('aria-expanded') === 'true');
    await finish();
    await capture.evaluate(() => document.querySelector('ex-work-timeline li:last-child ex-tool-step .head')?.scrollIntoView({ block: 'center' }));
    await capture.click('ex-work-timeline li:last-child ex-tool-step .head');
    await finish();
    yield { name: `${theme}-tool-details`, inspect: ['ex-work-timeline', 'ex-tool-step'] };
    await mode('permission');
    await capture.waitFor(() => document.querySelector('ex-approval-card'));
    await capture.evaluate(() => document.querySelector('ex-approval-card')?.scrollIntoView({ block: 'center' }));
    await finish();
    assert.equal(await capture.evaluate(() => document.querySelector('ex-approval-card')?.textContent.includes('Always allow')), false);
    yield { name: `${theme}-approval`, inspect: ['ex-approval-card'] };
    await capture.click('ex-approval-card button[data-variant=primary]');
    await capture.waitFor(() => !document.querySelector('ex-approval-card'));
    await mode('question'); await capture.waitFor(() => document.querySelector('ex-question-card'));
    await capture.evaluate(() => document.querySelector('ex-question-card')?.scrollIntoView({ block: 'center' }));
    await finish();
    yield { name: `${theme}-question`, inspect: ['ex-question-card'] };
    await capture.click('ex-question-card fieldset label:first-of-type');
    await capture.waitFor(() => !document.querySelector('ex-question-card'));
    await capture.fill('ex-composer textarea', 'Verify the delayed response too.'); await capture.press('Enter');
    await capture.waitFor(() => document.querySelector('ex-session-chat .status')?.textContent.includes('Running'));
    await capture.fill('ex-composer textarea', 'Keep this follow-up draft');
    assert.equal(await capture.evaluate(() => document.querySelector('ex-composer textarea').disabled), false);
    yield { name: `${theme}-streaming`, inspect: ['ex-composer', 'ex-turn:last-of-type'] };
    await capture.waitFor(() => !document.querySelector('ex-session-chat .status')?.textContent.includes('Running'));
    await owner(component => component.store.selectSession({ taskId: '11', sessionId: '102' }));
    await capture.waitFor(() => document.querySelector('ex-composer textarea')?.value === '');
    await owner(component => component.store.selectSession({ taskId: '11', sessionId: '101' }));
    await capture.waitFor(() => document.querySelector('ex-composer textarea')?.value === 'Keep this follow-up draft');
    await mode('long');
    await capture.waitFor(() => [...document.querySelectorAll('ex-chat > .conversation button')].some(button => button.textContent.includes('Read full tool output')));
    await capture.evaluate(() => [...document.querySelectorAll('ex-chat button')].find(button => button.textContent.includes('Read full tool output'))?.scrollIntoView({ block: 'center' }));
    await capture.click('ex-chat-scroll .content > button');
    await capture.waitFor(() => document.querySelector('[aria-label="Full transcript content"] pre')?.textContent.includes('Verified concurrent request'));
    yield { name: theme + '-full-output', inspect: ['[aria-label="Full transcript content"]'] };
    await capture.click('[aria-label="Full transcript content"] footer button:last-child');
    await capture.waitFor(() => document.querySelector('[aria-label="Full transcript content"] footer span')?.textContent.includes('16001'));
    await capture.press('Escape');
    await capture.waitFor(() => !document.querySelector('ex-session-chat-content'));
    assert.equal(await capture.evaluate(() => document.activeElement?.textContent.includes('Read full tool output')), true);
    await capture.viewport(1000, 760); await capture.reducedMotion(true); await mode('failed');
    await capture.waitFor(() => document.querySelector('ex-turn .error'));
    yield { name: `${theme}-narrow-failed-reduced`, inspect: ['ex-session-chat', 'ex-composer', 'ex-turn .error'] };
    await capture.reducedMotion(false);
  }
  await capture.viewport(1440, 960); await mode('unknown');
  await capture.fill('ex-composer textarea', 'A send with uncertain delivery'); await capture.press('Enter');
  await capture.waitFor(() => document.querySelector('ex-session-chat .feedback.error')?.textContent.includes('may have completed'));
  await capture.waitFor(() => document.querySelector('ex-composer textarea')?.value === 'A send with uncertain delivery');
  yield { name: 'uncertain-delivery', inspect: ['ex-session-chat .feedback', 'ex-composer'] };
  await capture.click('ex-session-chat .feedback.error button');
  await capture.waitFor(() => document.querySelector('ex-session-chat .feedback:not(.error) button'));
  await capture.click('ex-session-chat .feedback:not(.error) button');
  await mode('history'); await capture.waitFor(() => document.querySelector('ex-session-chat .history-controls button'));
  await finish();
  await capture.evaluate(() => { document.querySelector('ex-chat-scroll .viewport').scrollTop = 0; });
  await capture.waitFor(() => document.querySelector('ex-chat-scroll .viewport').scrollTop < 1);
  await capture.settle();
  await capture.click('ex-session-chat .history-controls button');
  await capture.waitFor(() => document.querySelector('ex-session-chat .history-controls')?.textContent.includes('Viewing earlier'));
  yield { name: 'earlier-history', inspect: ['ex-chat-scroll', 'ex-session-chat .history-controls', 'ex-composer'] };
  await finish();
  await capture.evaluate(() => { document.querySelector('ex-chat-scroll .viewport').scrollTop = 0; });
  await capture.waitFor(() => document.querySelector('ex-chat-scroll .viewport').scrollTop < 1);
  await capture.settle();
  await capture.click('ex-session-chat .history-controls button:last-child');
  await capture.waitFor(() => !document.querySelector('ex-session-chat .history-controls')?.textContent.includes('Viewing earlier'));
}
